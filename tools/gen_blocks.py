#!/usr/bin/env python3
"""Generate Rust block registry from Minecraft data generator's reports/blocks.json.

Usage: python3 gen_blocks.py <path/to/blocks.json> <out.rs>
"""
import json, sys

src, out = sys.argv[1], sys.argv[2]
blocks = json.load(open(src))

entries = []
for name, data in blocks.items():
    states = sorted(data["states"], key=lambda s: s["id"])
    ids = [s["id"] for s in states]
    # Verify states of a block form one contiguous ID range (needed for base+offset lookup).
    if ids != list(range(ids[0], ids[0] + len(ids))):
        raise SystemExit(f"non-contiguous state ids for {name}")
    default = next((s["id"] for s in states if s.get("default")), ids[0])
    entries.append((name, ids[0], len(ids), default))

entries.sort(key=lambda e: e[1])
total_states = sum(e[2] for e in entries)
max_id = entries[-1][1] + entries[-1][2] - 1

lines = []
lines.append("// AUTO-GENERATED by gen_blocks.py from reports/blocks.json (Minecraft 26.3). Do not edit.")
lines.append("")
lines.append("#![allow(dead_code)]")
lines.append("")
lines.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
lines.append("pub struct BlockDef {")
lines.append("    pub name: &'static str,")
lines.append("    /// First global state ID of this block.")
lines.append("    pub base_id: u16,")
lines.append("    /// Number of block states (base_id..base_id + state_count).")
lines.append("    pub state_count: u16,")
lines.append("    /// Default state ID (what placing the block without properties gives).")
lines.append("    pub default_id: u16,")
lines.append("}")
lines.append("")
lines.append(f"pub const TOTAL_STATES: u16 = {total_states};")
lines.append(f"pub const MAX_STATE_ID: u16 = {max_id};")
lines.append("")
lines.append("/// Sorted by base_id, so state -> block lookup can binary search.")
lines.append("pub static BLOCKS: &[BlockDef] = &[")
for name, base, count, default in entries:
    lines.append(f'    BlockDef {{ name: "{name}", base_id: {base}, state_count: {count}, default_id: {default} }},')
lines.append("];")
lines.append("")
lines.append("/// Returns the block that owns this global state ID.")
lines.append("pub fn block_of_state(state: u16) -> Option<&'static BlockDef> {")
lines.append("    let idx = BLOCKS.partition_point(|b| b.base_id <= state);")
lines.append("    if idx == 0 { return None; }")
lines.append("    let b = &BLOCKS[idx - 1];")
lines.append("    if state < b.base_id + b.state_count { Some(b) } else { None }")
lines.append("}")
lines.append("")
lines.append("/// Finds a block by namespaced name, e.g. \"minecraft:stone\".")
lines.append("pub fn block_by_name(name: &str) -> Option<&'static BlockDef> {")
lines.append("    BLOCKS.iter().find(|b| b.name == name)")
lines.append("}")
lines.append("")

open(out, "w").write("\n".join(lines))
print(f"blocks: {len(entries)}, states: {total_states}, max id: {max_id}")
